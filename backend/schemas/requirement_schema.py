from pydantic import BaseModel, Field


class RequirementAnalysis(BaseModel):
    """
    Structured output generated by the Requirement Agent.
    """

    functional_requirements: list[str] = Field(
        description="List of functional requirements"
    )

    non_functional_requirements: list[str] = Field(
        description="List of non-functional requirements"
    )

    user_stories: list[str] = Field(
        description="List of user stories"
    )

    stakeholders: list[str] = Field(
        description="Stakeholders involved in the project"
    )

    assumptions: list[str] = Field(
        description="Assumptions made while generating requirements"
    )